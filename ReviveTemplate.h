inline bool FindReviveButton(const BYTE* bgr, int stride, int roiW, int roiH, int& outX, int& outY, double threshold = 0.68) {
    if (!bgr || roiW < REVIVE_TPL_W || roiH < REVIVE_TPL_H || stride <= 0) return false;

    std::vector<BYTE> gray(roiW * roiH);
    for (int y = 0; y < roiH; y++) {
        const BYTE* row = bgr + y * stride;
        for (int x = 0; x < roiW; x++) {
            BYTE b = row[x * 3];
            BYTE g = row[x * 3 + 1];
            BYTE r = row[x * 3 + 2];
            gray[y * roiW + x] = (BYTE)((r * 77 + g * 150 + b * 29) >> 8);
        }
    }

    double bestScore = -1.0;
    int bestX = -1, bestY = -1;

    for (int y = 0; y <= roiH - REVIVE_TPL_H; y += 2) {
        for (int x = 0; x <= roiW - REVIVE_TPL_W; x += 2) {
            double sum = 0.0, sumSq = 0.0;
            for (int ty = 0; ty < REVIVE_TPL_H; ty += 2) {
                const BYTE* pG = &gray[(y + ty) * roiW + x];
                for (int tx = 0; tx < REVIVE_TPL_W; tx += 2) {
                    double v = (double)pG[tx];
                    sum += v;
                    sumSq += v * v;
                }
            }
            double meanP = sum / (double)REVIVE_SUB_N;
            double varP = (sumSq / (double)REVIVE_SUB_N) - (meanP * meanP);
            if (varP < 15.0) continue;
            double stdP = std::sqrt(varP);

            double cross = 0.0;
            for (int ty = 0; ty < REVIVE_TPL_H; ty += 2) {
                const BYTE* pG = &gray[(y + ty) * roiW + x];
                const unsigned char* pT = &REVIVE_TPL_GRAY[ty * REVIVE_TPL_W];
                for (int tx = 0; tx < REVIVE_TPL_W; tx += 2) {
                    cross += ((double)pG[tx] - meanP) * ((double)pT[tx] - REVIVE_SUB_MEAN);
                }
            }
            double ncc = cross / ((double)REVIVE_SUB_N * stdP * REVIVE_SUB_STD);
            if (ncc > bestScore) {
                bestScore = ncc;
                bestX = x;
                bestY = y;
            }
        }
    }

    if (bestScore >= threshold && bestX >= 0) {
        // Validation: In-game [Revive] button has a characteristic blue-patterned background
        int blueVotes = 0;
        int totalChecked = 0;
        for (int cy = 16; cy <= 42; cy++) {
            const BYTE* row = bgr + (bestY + cy) * stride;
            for (int cx = 16; cx <= 38; cx++) {
                BYTE b = row[(bestX + cx) * 3];
                BYTE g = row[(bestX + cx) * 3 + 1];
                BYTE r = row[(bestX + cx) * 3 + 2];
                if (b > r + 10 && b >= 35) {
                    blueVotes++;
                }
                totalChecked++;
            }
        }
        if (totalChecked > 0 && ((double)blueVotes / totalChecked) >= 0.35) {
            outX = bestX + REVIVE_TPL_W / 2;
            outY = bestY + REVIVE_TPL_H / 2;
            return true;
        }
    }
    return false;
}
