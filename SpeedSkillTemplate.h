static const double SPEED_TPL_MEAN = 78.6488;
static const double SPEED_TPL_STD  = 56.0935;

inline bool FindSpeedSkillIcon(const BYTE* bgr, int stride, int roiW, int roiH, int& outX, int& outY, double threshold = 0.65) {
    if (!bgr || roiW < SPEED_TPL_W || roiH < SPEED_TPL_H || stride <= 0) return false;

    std::vector<BYTE> gray(roiW * roiH);
    for (int y = 0; y < roiH; y++) {
        const BYTE* row = bgr + y * stride;
        BYTE* gRow = gray.data() + y * roiW;
        for (int x = 0; x < roiW; x++) {
            int b = row[x * 3];
            int g = row[x * 3 + 1];
            int r = row[x * 3 + 2];
            gRow[x] = (BYTE)((r * 77 + g * 150 + b * 29) >> 8);
        }
    }

    int nPixels = SPEED_TPL_W * SPEED_TPL_H;
    double bestScore = -1.0;
    int bestX = -1, bestY = -1;

    for (int y = 0; y <= roiH - SPEED_TPL_H; y++) {
        for (int x = 0; x <= roiW - SPEED_TPL_W; x++) {
            double sumP = 0.0, sumP2 = 0.0, sumPT = 0.0;
            for (int ty = 0; ty < SPEED_TPL_H; ty++) {
                const BYTE* pRow = gray.data() + (y + ty) * roiW + x;
                const unsigned char* tRow = SPEED_TPL_GRAY + ty * SPEED_TPL_W;
                for (int tx = 0; tx < SPEED_TPL_W; tx++) {
                    double p = pRow[tx];
                    double t = tRow[tx];
                    sumP += p;
                    sumP2 += p * p;
                    sumPT += p * t;
                }
            }
            double meanP = sumP / nPixels;
            double varP = (sumP2 / nPixels) - (meanP * meanP);
            if (varP < 10.0) continue;
            double stdP = std::sqrt(varP);

            double covar = (sumPT / nPixels) - (meanP * SPEED_TPL_MEAN);
            double ncc = covar / (stdP * SPEED_TPL_STD);

            if (ncc > bestScore) {
                bestScore = ncc;
                bestX = x;
                bestY = y;
            }
        }
    }

    if (bestScore >= threshold && bestX != -1) {
        outX = bestX + SPEED_TPL_W / 2;
        outY = bestY + SPEED_TPL_H / 2;
        return true;
    }
    return false;
}

