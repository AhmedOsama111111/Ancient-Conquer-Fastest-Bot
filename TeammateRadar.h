// Detect the glowing purple 4-point star beacon on the minimap
inline bool DetectTeammateBeacon(const uint32_t* pixels, int winW, int winH, int& outBeaconX, int& outBeaconY) {
    if (!pixels || winW < 800 || winH < 500) return false;

    // Minimap bounds at top right
    int mmW = (winW > 1366 ? 160 : 130);
    int mmH = (winW > 1366 ? 155 : 125);
    int mmLeft = winW - mmW;
    int mmTop = 0;

    double sumX = 0.0, sumY = 0.0;
    int purpleCount = 0;

    for (int y = mmTop; y < mmTop + mmH && y < winH; y++) {
        int row = y * winW;
        for (int x = mmLeft; x < mmLeft + mmW && x < winW; x++) {
            uint32_t c = pixels[row + x];
            int b = (int)(c & 0xFF);
            int g = (int)((c >> 8) & 0xFF);
            int r = (int)((c >> 16) & 0xFF);

            // Distinct Purple/Lavender Star Beacon pixels:
            // B > 190 && R > 130 && G < 210 && (B - G) >= 28
            if (b > 190 && r > 130 && g < 210 && (b - g) >= 28) {
                sumX += (x - mmLeft);
                sumY += (y - mmTop);
                purpleCount++;
            }
        }
    }

    if (purpleCount >= 15) {
        outBeaconX = (int)std::round(sumX / purpleCount);
        outBeaconY = (int)std::round(sumY / purpleCount);
        return true;
    }

    return false;
}

// Detect if teammate avatar is BRIGHT (player reached teammate) or DARK (away)
inline bool IsTeammateAvatarBright(const uint32_t* pixels, int winW, int winH) {
    if (!pixels || winW < 800 || winH < 500) return false;

    // Teammate avatar is on the right side under minimap:
    // Centered around (winW - 64, 275) for 1080p, or (winW - 55, 225) for 576p
    int faceX = (winW > 1366 ? (winW - 95) : (winW - 80));
    int faceY = (winW > 1366 ? 235 : 190);
    int faceW = 48;
    int faceH = 48;

    double sumLum = 0.0;
    int count = 0;
    double dotBright = 0.0, dotDark = 0.0;
    double normPatch = 0.0, normBright = 0.0, normDark = 0.0;

    for (int y = 0; y < faceH; y++) {
        int py = faceY + y;
        if (py >= winH) break;
        int row = py * winW;
        for (int x = 0; x < faceW; x++) {
            int px = faceX + x;
            if (px >= winW) break;
            uint32_t c = pixels[row + px];
            int b = (int)(c & 0xFF);
            int g = (int)((c >> 8) & 0xFF);
            int r = (int)((c >> 16) & 0xFF);
            double gray = 0.299 * r + 0.587 * g + 0.114 * b;
            sumLum += gray;
            count++;

            int idx = y * faceW + x;
            double tb = (double)FACE_BRIGHT_GRAY[idx];
            double td = (double)FACE_DARK_GRAY[idx];

            dotBright  += gray * tb;
            dotDark    += gray * td;
            normPatch  += gray * gray;
            normBright += tb * tb;
            normDark   += td * td;
        }
    }

    if (count == 0) return false;
    double avgLum = sumLum / count;

    double scoreB = (normPatch > 0 && normBright > 0) ? (dotBright / (std::sqrt(normPatch) * std::sqrt(normBright))) : 0.0;
    double scoreD = (normPatch > 0 && normDark > 0)   ? (dotDark   / (std::sqrt(normPatch) * std::sqrt(normDark)))   : 0.0;

    // True = BRIGHT (Near teammate), False = DARK (Away)
    // Primary criteria: scoreB > scoreD OR avgLum >= 63.0
    return (scoreB > scoreD || avgLum >= 63.0);
}
